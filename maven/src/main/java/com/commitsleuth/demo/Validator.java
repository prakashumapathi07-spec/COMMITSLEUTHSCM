package com.commitsleuth.demo;

public class Validator {
    public boolean isPositive(int n) { return n > 0; }
    public boolean isEven(int n) { return n % 2 == 0; }
    public boolean isInRange(int n, int min, int max) { return n >= min && n <= max; }
}
